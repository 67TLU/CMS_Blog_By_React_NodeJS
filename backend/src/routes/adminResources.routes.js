import { Router } from 'express';
import { authenticate } from '../middlewares/authenticate.js';
import { requireRole } from '../middlewares/authorize.js';
import { asyncHandler } from '../middlewares/asyncHandler.js';
import * as c from '../controllers/extended.controller.js';
const router=Router();
router.use(authenticate,requireRole('ADMIN','EDITOR'));
router.get('/dashboard',asyncHandler(c.adminDashboard));
router.get('/users',asyncHandler(c.adminUsers));
router.patch('/users/:id/status',asyncHandler(c.adminSetUserStatus));
router.patch('/users/:id/role',requireRole('ADMIN'),asyncHandler(c.adminSetUserRole));
router.get('/tags',asyncHandler(c.adminListTags));
router.post('/tags',requireRole('ADMIN','EDITOR'),asyncHandler(c.adminCreateTag));
router.delete('/tags/:id',requireRole('ADMIN','EDITOR'),asyncHandler(c.adminDeleteTag));
router.get('/menu',asyncHandler(c.adminListMenu));
router.post('/menu',requireRole('ADMIN'),asyncHandler(c.adminCreateMenu));
router.patch('/menu/:id',requireRole('ADMIN'),asyncHandler(c.adminUpdateMenu));
router.delete('/menu/:id',requireRole('ADMIN'),asyncHandler(c.adminDeleteMenu));
router.put('/menu/reorder',requireRole('ADMIN'),asyncHandler(c.adminReorderMenu));
router.get('/roles',requireRole('ADMIN'),asyncHandler(c.adminRoles));
router.put('/roles/:code/permissions',requireRole('ADMIN'),asyncHandler(c.adminUpdateRolePermissions));
router.get('/advertisements',asyncHandler(c.adminListAds));
router.post('/advertisements',requireRole('ADMIN'),asyncHandler(c.adminCreateAd));
router.patch('/advertisements/:id',requireRole('ADMIN'),asyncHandler(c.adminUpdateAd));
router.delete('/advertisements/:id',requireRole('ADMIN'),asyncHandler(c.adminDeleteAd));
router.get('/audit-logs',asyncHandler(c.adminAuditLogs));
router.get('/settings',requireRole('ADMIN'),asyncHandler(c.adminGetSettings));
router.put('/settings',requireRole('ADMIN'),asyncHandler(c.adminPutSettings));
router.get('/categories/tree',asyncHandler(c.getAdminCategoryTree));
export default router;
